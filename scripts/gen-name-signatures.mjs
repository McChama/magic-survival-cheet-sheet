// Rebuilds src/capture/nameSignatures.ts: what each Class and Test Subject name looks like on screen, so the
// reader can tell which one a menu shows without a screenshot of every one of them. The names are drawn
// here with the app's copy of the game font (public/assets/magicSurvival.ttf — its family is "Untitled1")
// and reduced exactly like a title read off the screen (`textSignature`). Drawn text and the real thing
// agree at ~0.85-0.90 where a wrong name scores ~0.70 — see the class/test-subject fixtures in check:capture.
//
//   npm run capture:names

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { peak } from "../src/capture/frame.ts";
import { textSignature } from "../src/capture/recognize.ts";
import { CLASSES, SUBJECTS } from "../src/data/classes.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const font = resolve(root, "public/assets/magicSurvival.ttf");

async function signatureOf(name) {
  const text = name.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  const { data, info } = await sharp({ text: { text: `<span foreground="white">${text}</span>`, font: "Untitled1 60", fontfile: font, rgba: true, dpi: 150 } })
    .flatten({ background: "#000" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const frame = { width: info.width, height: info.height, data };
  const signature = textSignature({ x: 0, y: 0, w: frame.width, h: frame.height }, (x, y) => peak(frame, x, y) > 128);
  if (!signature) throw new Error(`Nothing drawn for "${name}"`);
  return signature;
}

async function table(names) {
  const lines = [];
  for (const name of names) {
    const signature = await signatureOf(name);
    lines.push(`  ${JSON.stringify(name)}: { aspect: ${signature.aspect.toFixed(3)}, bits: "${signature.bits}" },`);
  }
  return lines.join("\n");
}

writeFileSync(
  resolve(root, "src/capture/nameSignatures.ts"),
  `// Generated by \`npm run capture:names\` (the names drawn with the game font) — do not edit by hand.
import type { TitleSignature } from "./recognize";

// prettier-ignore
export const CLASS_NAME_SIGNATURES: Record<string, TitleSignature> = {
${await table(CLASSES)}
};

// prettier-ignore
export const SUBJECT_NAME_SIGNATURES: Record<string, TitleSignature> = {
${await table(SUBJECTS)}
};
`
);
console.log(`Wrote ${CLASSES.length} class and ${SUBJECTS.length} subject name signatures.`);
