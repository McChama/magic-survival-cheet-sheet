// Rebuilds src/capture/titleSignatures.ts: the coarse bitmap of each game screen's title, taken
// from the reference screenshots. Run it when a fixture is replaced or a title band changes.
//
//   npm run capture:signatures

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { obtainSignature, titleSignature } from "../src/capture/recognize.ts";
import { loadFixture } from "./capture-node.mjs";

const SOURCES = {
  selectMagic: "select-magic",
  selectAttribute: "select-attribute",
  treasureChest: "treasure-chest",
  pause: "pause",
  ownedMagic: "owned-magic",
  ownedArtifact: "owned-artifact",
  synergy: "synergy",
  enterArea: "enter-area",
  lifeOrDeath: "life-or-death",
  classSelect: "class",
  testSubject: "test-subject",
  research: "research",
};

const lines = [];
for (const [screen, fixture] of Object.entries(SOURCES)) {
  const signature = titleSignature(await loadFixture(fixture), screen);
  if (!signature) throw new Error(`No title found for ${screen} in ${fixture}.jpg`);
  lines.push(`  ${screen}: { aspect: ${signature.aspect.toFixed(3)}, bits: "${signature.bits}" },`);
}

const obtain = obtainSignature(await loadFixture("treasure-chest"));
if (!obtain) throw new Error("No Obtain label found in treasure-chest.jpg");

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/capture/titleSignatures.ts");
writeFileSync(
  out,
  `// Generated by \`npm run capture:signatures\` from scripts/capture-fixtures/ — do not edit by hand.
import type { ScreenId } from "./geometry";
import type { TitleSignature } from "./recognize";

// prettier-ignore
export const TITLE_SIGNATURES: Record<ScreenId, TitleSignature> = {
${lines.join("\n")}
};

/** The "Obtain" label of the artifact-offer panel (Treasure Chest, Obelisk, ...). */
// prettier-ignore
export const OBTAIN_SIGNATURE: TitleSignature = { aspect: ${obtain.aspect.toFixed(3)}, bits: "${obtain.bits}" };
`
);
console.log(`Wrote ${lines.length} title signatures.`);
